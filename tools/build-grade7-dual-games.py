   launcher=template.replace('THCS Trực Tuấn',html.escape(row['school'])).replace('English Quest 6','English Quest 7').replace('GRADE 6','GRADE 7').replace('LỚP 6','LỚP 7').replace('Quest <b>6</b>','Quest <b>7</b>').replace('dual-mode-engine.js?v=20261026-grade6','dual-mode-engine.js?v=20261026-grade7').replace(quote('3 THCS Truc Tuan.html'),quote(Path(row['source']).name)).replace('43',str(row['questions']))
