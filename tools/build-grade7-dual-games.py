 for i,a in enumerate(media['audio']):
  src=html.unescape(a['src']);original=path.parent/unquote(src);assert original.is_file();track=dict(id='listen-'+str(i+1),title='Listening · '+('Toàn bộ bài nghe' if len(media['audio'])==1 else 'Phần '+str(i+1)),src=src,wholeFile=len(media['audio'])==1,sourceSrc=src,sourceSha256=sha(original.read_bytes()),sha256=sha(original.read_bytes()))
  # Original WMA is preserved. A separately verified MP3 compatibility derivative
  # may be provided by the build owner after native browser rejection is proven.
  if original.suffix.lower()=='.wma' and (path.parent/'listening-2024-browser.mp3').is_file():
   track['src']='listening-2024-browser.mp3';track['sha256']=sha((path.parent/track['src']).read_bytes());track['compatibilityDerivative']=True
  tracks.append(track)
 for q in questions:
  if q['sourceSection']!=0:continue
  # Match the preceding source player. No hard-coded question-count split.
  preceding=[t for t in media['audio'] if t['position']<q['sourcePosition']]
  if tracks:q['track']=tracks[max(0,len(preceding)-1)]['id']
  else:
   originalContext=context[q['context']] if 'context' in q else ''
   q['contextHtml']='<p><strong>Nguồn đề chưa có file Listening được liên kết. Mở đề gốc và hỏi giáo viên để xác nhận file nghe.</strong></p>'+originalContext
   q.pop('context',None)
  transcripts=media['transcripts'];preceding_scripts=[t for t in transcripts if t['position']<q['sourcePosition']]
  part=listen_section_ids.index(q['section']) if len(listen_section_ids)==2 else (max(0,len(preceding)-1) if len(tracks)==2 else None)
  if len(transcripts)==2 and part is not None:q['transcriptHtml']=transcripts[part]['html']
  elif transcripts:
   # A combined source container is preserved whole instead of guessing a split.
   q['transcriptHtml']='\n'.join(t['html'] for t in transcripts)
 data=dict(schemaVersion=1,exam=dict(id='grade7-ghk1-source-'+str(row['folder']),grade=7,school=row['school'],number=row['number'],title=f'Đề số {row["number"]} · Giữa học kỳ I · Tiếng Anh 7',sourceHtml=path.name,sourceBaseline='d1f7ebf',sourceSha256=row['sourceSha256']),questions=questions,sections=sections,contexts=context,tracks=tracks)
 return g8.finish(data)
