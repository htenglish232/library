def build(row,page):
 path=ROOT/row['source'];source=path.read_text();assert sha(path.read_bytes())==row['sourceSha256']
 raw=json.loads(re.search(r'<script[^>]*id="examData"[^>]*>([\s\S]*?)</script>',source)[1]);items=raw['questions'];assert len(items)==row['questions']
 parts=page.evaluate('''s=>{const d=new DOMParser().parseFromString(s,'text/html');return [...d.querySelectorAll('.question-card[data-qid]')].map(e=>({id:e.dataset.qid,section:Number(e.closest('[data-section]').dataset.section),rewrite:e.classList.contains('rewrite-card'),fallbackPrompt:e.previousElementSibling?.textContent.trim()||'',fields:[...e.querySelectorAll('[data-answer-field]')].map(f=>({id:f.id,type:f.type})),prefix:e.querySelector('.rewrite-prefix')?.textContent||''}));}''',source)
 assert len(parts)==len(items);byId={q['id']:q for q in items};assert {p['id'] for p in parts}==set(byId)
 extracted=page.evaluate((ROOT/'tools/grade6-source-dom.js').read_text(),dict(source=source,specs=[dict(id=p['id']) for p in parts],stripSelectors=STRIP));rById={r['id']:r for r in extracted}
 context=[];sections=[];questions=[];previous=None
 listen_section_ids=[]
 for p in parts:
  qraw=byId[p['id']];r=rById[p['id']];
  if not r['promptHtml']:
   assert p['fallbackPrompt'],'Missing source prompt '+p['id'];r['promptHtml']='<p>'+html.escape(p['fallbackPrompt'])+'</p>'
  assert p['section']==qraw['section'];key=(p['section'],r['subheading'])
  if key!=previous:
   sid='section-'+str(len(sections)+1);heading=r['subheading'] or ['Listening Challenge','Vocabulary & Grammar Battle','Reading Quest','Writing Challenge'][p['section']]
   sections.append(dict(id=sid,title=heading,description=r['heading'] or heading,icon=['🎧','⚡','📖','🧩'][p['section']]));previous=key
  mapped=copy.deepcopy(qraw);mapped['explanation']=qraw.get('explanation','')
  wd={'tokens':qraw['tokens']} if qraw['kind']=='chips' and not p['rewrite'] else None
  item=g6.question(mapped,r,sid,len(questions)+1,wd);item['sourcePosition']=r['sourcePosition'];item['sourceSection']=p['section'];item['sourceRewrite']=p['rewrite'];item['sourcePrefix']=p['prefix'];item['sourceTokens']=qraw.get('tokens',[])
  if p['rewrite']:
   assert any(f['type']=='text' for f in p['fields']);assert item['kind']=='text'
   item['promptHtml']+='<p>Nhập phần còn lại của câu sau phần đầu đã cho.</p>'
  if qraw.get('parts'):
   assert len(qraw['parts'])==len(p['fields']);item['kind']='multi-text';item['inputCount']=len(p['fields']);item['acceptedTuples']=[list(t) for t in itertools.product(*qraw['parts'])]
  # A source key may strip punctuation (didnt), while its literal model answer
  # keeps it (didn’t). Accept only an actual source <strong>/<b> answer whose
  # words match that key and whose exact tiles can form it; never invent text.
  if wd and any('Thẻ từ nguồn' in flag for flag in item['teacherFlags']):
   normalize=lambda value:' '.join(re.sub(r'[^\w\s]','',value.lower()).split())
   candidates=[html.unescape(re.sub('<[^>]+>','',m)) for m in re.findall(r'<(?:strong|b)[^>]*>([\s\S]*?)</(?:strong|b)>',qraw.get('explanation',''),re.I)]
   proven=[c for c in candidates if any(normalize(c)==normalize(a) for a in qraw['accepted']) and g8.realizable(qraw['tokens'],[c])]
   if proven:
    item['accepted']=list(dict.fromkeys(item['accepted']+proven));item['answerEvidence'].append(dict(kind='literal-explanation-matches-key-and-tiles',value=proven))
    item['teacherFlags']=[flag for flag in item['teacherFlags'] if 'Thẻ từ nguồn' not in flag];item['autoGrade']=not item['teacherFlags']
  # Use exact explicit whole answers, never reproduce permissive keyword,
  # substring, overlap or startsYes grading from the original application.
  if not qraw.get('accepted') and qraw.get('groups'):
   item['teacherFlags'].append('Nguồn chỉ có nhóm từ khóa, chưa có tập đáp án đầy đủ; cần giáo viên kiểm tra.')
   item['autoGrade']=False
  if any(' / ' in a or '\n' in a for a in item['accepted']):
   item['teacherFlags'].append('Đáp án nguồn ghép nhiều cách viết trong một chuỗi; không tự tách/suy đoán biến thể, cần giáo viên kiểm tra.');item['autoGrade']=False
  if qraw.get('prefix') and item['accepted']:
   # This is the exact documented source matcher: optional literal prefix.
   item['accepted']=list(dict.fromkeys(item['accepted']+[qraw['prefix']+a for a in item['accepted']]))
   item['answerEvidence'].append(dict(kind='source-prefix-rule',value=qraw['prefix']))
  if re.search(r'underlined|gạch chân',item['promptHtml'],re.I) and not re.search(r'<u[ >]',item['promptHtml']+''.join(o['html'] for o in item['options']),re.I):
   item['teacherFlags'].append('Nguồn không đánh dấu phần gạch chân; không tự suy đoán, cần giáo viên kiểm tra.');item['autoGrade']=False
  ctx=r['contextHtml']
  if ctx:
   if ctx not in context:context.append(ctx)
   item['context']=context.index(ctx)
  if p['section']==0 and sid not in listen_section_ids:listen_section_ids.append(sid)
  questions.append(item)
 # Audio and transcript association uses actual source DOM order. A single
 # original recording remains one whole-file track; never fabricate split times.
